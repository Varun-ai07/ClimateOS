def get_city_key(municipality_id: str) -> str:
    """Extract city key from municipality ID."""
    return municipality_id.replace('_in', '').lower()


def load_city_data(city_key: str, feature_type: str) -> list:
    """Load city-specific GeoJSON data."""
    city_dir = PROCESSED_DIR / city_key
    filepath = city_dir / f'{feature_type}.geojson'
    
    if not filepath.exists():
        # Fallback to Coimbatore
        filepath = PROCESSED_DIR / 'coimbatore' / f'{feature_type}.geojson'
    
    if filepath.exists():
        with open(filepath) as f:
            data = json.load(f)
        return data.get('features', [])
    return []


def generate_dem_risk_zones(city_key: str, water_features: list, excess_pct: float) -> list:
    """Generate DEM-based risk zones using elevation and water proximity."""
    city_info = CITY_DATA.get(city_key, CITY_DATA['coimbatore'])
    base_elevation = city_info['elevation_m']
    
    # Create grid-based risk zones
    risk_zones = []
    grid_size = 0.02  # ~2km grid
    
    # Get water points
    water_points = []
    for feat in water_features[:100]:
        lat = feat['properties'].get('lat', 0)
        lon = feat['properties'].get('lon', 0)
        if lat and lon:
            water_points.append((lat, lon))
    
    # Generate zones in a grid around the city center
    for i in range(-3, 4):
        for j in range(-3, 4):
            zone_lat = city_info['lat'] + i * grid_size
            zone_lon = city_info['lon'] + j * grid_size
            
            # Calculate distance to nearest water
            min_water_dist = float('inf')
            for wlat, wlon in water_points:
                dist = ((zone_lat - wlat) ** 2 + (zone_lon - wlon) ** 2) ** 0.5 * 111000
                min_water_dist = min(min_water_dist, dist)
            
            # Simulate elevation (varies with distance from center)
            dist_from_center = (i**2 + j**2) ** 0.5
            zone_elevation = base_elevation + (dist_from_center * 5) - 10  # Rough DEM simulation
            
            # Risk classification
            if min_water_dist < 500 and excess_pct > 10:
                risk = 'high'
            elif min_water_dist < 1000 or (zone_elevation < base_elevation and excess_pct > 5):
                risk = 'medium'
            else:
                risk = 'low'
            
            if risk in ('high', 'medium'):
                risk_zones.append(RiskZone(
                    zone_id=f'zone_{i+3}_{j+3}',
                    risk_level=risk,
                    center_lat=zone_lat,
                    center_lon=zone_lon,
                    area_km2=grid_size * grid_size * 111 * 111,  # Approximate
                    water_proximity_count=len([w for w in water_points if ((zone_lat-w[0])**2 + (zone_lon-w[1])**2)**0.5 * 111000 < 1000]),
                    affected_population=int(500 * (1 if risk == 'high' else 0.5)),
                ))
    
    return risk_zones[:15]  # Limit to 15 zones


class ImpactAgent(BaseAgent):
    name = "impact_agent"
    description = "Maps climate risks onto local infrastructure using processed OSM data"

    async def execute(self, state: MunicipalityClimateState) -> MunicipalityClimateState:
        self.add_timeline_event(state, "impact_start", f"Analyzing infrastructure in {state.municipality_name}...")

        city_key = get_city_key(state.municipality_id)
        city_info = CITY_DATA.get(city_key, CITY_DATA['coimbatore'])
        
        precip = state.downscaled.corrected_precip_mm
        excess_pct = max(0, (precip - 200) / 200 * 100)

        # Load city-specific data
        hospitals = load_city_data(city_key, 'hospitals')
        schools = load_city_data(city_key, 'schools')
        water = load_city_data(city_key, 'water')
        buildings = load_city_data(city_key, 'buildings')

        # Get water points for proximity calculation
        water_points = [(f["properties"].get("lat", 0), f["properties"].get("lon", 0))
                       for f in water[:200] if f["properties"].get("lat")]

        # Risk assessment
        affected_hospitals = self._assess_infra(hospitals, water_points, excess_pct, "hospital")
        affected_schools = self._assess_infra(schools, water_points, excess_pct, "school")
        affected_buildings = self._assess_infra(buildings[:200], water_points, excess_pct, "building")

        # Generate DEM-based risk zones
        risk_zones = generate_dem_risk_zones(city_key, water, excess_pct)

        # Calculate stats
        high_hospitals = sum(1 for h in affected_hospitals if h.risk_level == "high")
        high_schools = sum(1 for s in affected_schools if s.risk_level == "high")

        # Determine overall risk level
        risk_score = min(100, int(excess_pct + 50))
        if risk_score >= 80:
            risk_level = "critical"
        elif risk_score >= 60:
            risk_level = "high"
        elif risk_score >= 40:
            risk_level = "medium"
        else:
            risk_level = "low"

        state.impact = ImpactAssessment(
            affected_hospitals=affected_hospitals[:20],
            affected_schools=affected_schools[:20],
            affected_buildings=affected_buildings[:50],
            risk_zones=risk_zones,
            overall_risk_score=risk_score,
            risk_level=risk_level,
            population_affected=(high_hospitals * 500 + high_schools * 300 + len(affected_buildings) * 50),
            buildings_affected=len(affected_buildings),
            hospitals_affected=len(affected_hospitals),
            schools_affected=len(affected_schools),
            critical_infrastructure_count=high_hospitals + high_schools,
        )

        self.add_timeline_event(state, "impact_complete",
            f"Risk: {risk_score}/100 ({risk_level}) | "
            f"{len(affected_hospitals)} hospitals, {len(affected_schools)} schools at risk")

        # Map updates
        self.add_map_update(state, "risk_polygons", {
            "city": city_info['name'],
            "center": [city_info['lat'], city_info['lon']],
            "zones": [{"id": z.zone_id, "risk": z.risk_level, "lat": z.center_lat, "lon": z.center_lon} for z in risk_zones]
        })
        self.add_map_update(state, "highlight_hospitals", {
            "hospitals": [{"name": h.name, "risk": h.risk_level, "lat": h.lat, "lon": h.lon}
                         for h in affected_hospitals[:10]]
        })
        self.add_map_update(state, "highlight_schools", {
            "schools": [{"name": s.name, "risk": s.risk_level, "lat": s.lat, "lon": s.lon}
                       for s in affected_schools[:10]]
        })
        self.add_map_update(state, "dem_data", {
            "city": city_info['name'],
            "elevation_m": city_info['elevation_m'],
            "risk_zones_count": len(risk_zones),
        })

        return state

    def _assess_infra(self, features, water_points, excess_pct, infra_type):
        """Assess risk for infrastructure based on proximity to water."""
        affected = []

        for feat in features[:100]:
            props = feat.get("properties", {})
            lon, lat = props.get("lon", 0), props.get("lat", 0)

            if not lat or not lon:
                continue

            # Calculate distance to nearest water
            min_dist = float("inf")
            for wlat, wlon in water_points:
                dist = ((lon - wlon) ** 2 + (lat - wlat) ** 2) ** 0.5 * 111000
                min_dist = min(min_dist, dist)

            # Risk classification
            if min_dist < 200 and excess_pct > 10:
                risk = "high"
            elif min_dist < 500 or excess_pct > 5:
                risk = "medium"
            else:
                risk = "low"

            if risk in ("high", "medium"):
                affected.append(AffectedInfrastructure(
                    name=props.get("name", f"Unknown {infra_type}"),
                    type=infra_type,
                    risk_level=risk,
                    lat=lat,
                    lon=lon,
                    distance_to_water_m=min_dist,
                ))

        return affected
